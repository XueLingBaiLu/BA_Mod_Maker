#   bone_hash = zlib.crc32( 从 "root" 节点起的骨骼层级路径, UTF-8, '/' 连接 )
#   - 跳过 "root_scale" 缩放辅助节点；
#   - 多索引槽位名取首个 _N（"weapon_0_1_2" -> "weapon_0"，"turret_0_0" -> "turret_0"，
#     非纯数字尾缀不截断，如 "frontwing3_3_L" 保持原样）；
#   - 例：crc32("root/body") = 0x65A7524A，crc32("root/body/turret_0") = 0x2A839EFE，
#          crc32("root/body/turret_0/weapon_0") = 0xBF21869B。
#   KNOWN_HASHES 表的每个值 = 该名字最常见层级路径的 crc32（同一名字在不同 prefab
#   中路径不同时哈希不同——这就是本表"多值"的原因）。
import zlib

def bone_hash(path_segments):
    """按破解算法计算骨骼哈希。

    path_segments: 骨骼层级（含 "root"，不含 prefab 名），如
      ["root", "body", "turret_0"] → 0x2A839EFE
      或字符串 "root/body/turret_0"。
    返回 uint32。
    """
    if isinstance(path_segments, str):
        segs = path_segments.replace("\\", "/").split("/")
    else:
        segs = list(path_segments)
    segs = [s for s in segs if s and s != "root_scale"]

    def norm(s):
        if "_" in s:
            head, tail = s.split("_", 1)
            if tail and all(t.isdigit() for t in tail.split("_")):
                return head + "_" + tail.split("_")[0]
        return s

    path = "/".join(norm(s) for s in segs)
    return zlib.crc32(path.encode("utf-8")) & 0xFFFFFFFF


def self_test():
    """算法自检：标准路径与已知值对照。"""
    cases = [
        ("root", 0x16F4F95B),
        ("root/body", 0x65A7524A),
        ("root/body/turret_0", 0x2A839EFE),
        ("root/body/turret_0/weapon_0", 0xBF21869B),
        ("root/body/turret_0/weapon_0_1_2/recoil_0", 0x5A6309D7),
        ("root/root_scale/body", 0x65A7524A),  # root_scale 被跳过
        ("root/body/frontwing3_3_L", 0x337D3575),  # 非纯数字尾缀不截断
    ]
    ok = 0
    for path, exp in cases:
        v = bone_hash(path)
        mark = "OK" if v == exp else "FAIL(期望0x%08X)" % exp
        if v == exp:
            ok += 1
        print("  %-46s -> 0x%08X %s" % (path, v, mark))
    print("self_test: %d/%d" % (ok, len(cases)))
    return ok == len(cases)


